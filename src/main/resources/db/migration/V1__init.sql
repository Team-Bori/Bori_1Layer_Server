-- enum 값은 Java enum 이름(대문자)과 같게 VARCHAR + CHECK로 둔다.

CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  email VARCHAR(255) NOT NULL,
  name VARCHAR(50) NOT NULL,
  student_no VARCHAR(10),
  role VARCHAR(20) NOT NULL DEFAULT 'STUDENT' CHECK (role IN ('STUDENT', 'ADMIN')),
  notify_enabled BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP NOT NULL,
  password VARCHAR(255) NOT NULL,
  PRIMARY KEY (id)
);
CREATE TABLE notification (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  user_id BIGINT NOT NULL,
  type VARCHAR(20) NOT NULL CHECK (type IN ('QUEUE_READY', 'RETURN_APPROVED')),
  message VARCHAR(255) NOT NULL,
  read_at TIMESTAMP,
  created_at TIMESTAMP NOT NULL,
  PRIMARY KEY (id),
  FOREIGN KEY (user_id) REFERENCES users (id)
);
CREATE TABLE host_pi (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  name VARCHAR(128) NOT NULL,
  last_used_at TIMESTAMP,
  serial_code VARCHAR(128) NOT NULL,
  token_hash VARCHAR(255) NOT NULL,
  PRIMARY KEY (id)
);
CREATE TABLE cloud_board (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  pi_id BIGINT NOT NULL,
  name VARCHAR(100) NOT NULL,
  spec TEXT NOT NULL,
  board_type VARCHAR(20) NOT NULL CHECK (board_type IN ('JETSON', 'SBC', 'MCU')),
  host VARCHAR(255) NOT NULL,
  upload_limit_mb INTEGER NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'NORMAL' CHECK (status IN ('NORMAL', 'MAINTENANCE', 'BROKEN')),
  created_at TIMESTAMP NOT NULL,
  updated_at TIMESTAMP NOT NULL,
  serial_code VARCHAR(128) NOT NULL,
  usb_slot VARCHAR(32) NOT NULL,
  is_online BOOLEAN NOT NULL,
  execute_able BOOLEAN NOT NULL,
  deleted_at TIMESTAMP,
  PRIMARY KEY (id),
  FOREIGN KEY (pi_id) REFERENCES host_pi (id)
);
CREATE TABLE ai_model (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  name VARCHAR(100) NOT NULL,
  format VARCHAR(30) NOT NULL,
  description TEXT,
  created_at TIMESTAMP NOT NULL,
  PRIMARY KEY (id)
);
CREATE TABLE board_model (
  cloud_board_id BIGINT NOT NULL,
  ai_model_id BIGINT NOT NULL,
  PRIMARY KEY (cloud_board_id, ai_model_id),
  FOREIGN KEY (cloud_board_id) REFERENCES cloud_board (id),
  FOREIGN KEY (ai_model_id) REFERENCES ai_model (id)
);
CREATE TABLE user_model_upload (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  user_id BIGINT NOT NULL,
  cloud_board_id BIGINT NOT NULL,
  github_url VARCHAR(500) NOT NULL,
  model_format VARCHAR(30) NOT NULL,
  size_mb INTEGER NOT NULL,
  created_at TIMESTAMP NOT NULL,
  PRIMARY KEY (id),
  FOREIGN KEY (user_id) REFERENCES users (id),
  FOREIGN KEY (cloud_board_id) REFERENCES cloud_board (id)
);
CREATE TABLE board_session (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  user_id BIGINT NOT NULL,
  cloud_board_id BIGINT NOT NULL,
  ai_model_id BIGINT,
  upload_id BIGINT,
  started_at TIMESTAMP NOT NULL,
  last_active_at TIMESTAMP NOT NULL,
  ended_at TIMESTAMP,
  end_reason VARCHAR(20) CHECK (end_reason IN ('NORMAL', 'IDLE', 'FAILED', 'FORCED')),
  PRIMARY KEY (id),
  FOREIGN KEY (user_id) REFERENCES users (id),
  FOREIGN KEY (cloud_board_id) REFERENCES cloud_board (id),
  FOREIGN KEY (ai_model_id) REFERENCES ai_model (id),
  FOREIGN KEY (upload_id) REFERENCES user_model_upload (id)
);
CREATE TABLE metric_sample (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  session_id BIGINT NOT NULL,
  sampled_at TIMESTAMP(3) NOT NULL,
  cpu_pct DECIMAL(5, 2),
  mem_pct DECIMAL(5, 2),
  fps DECIMAL(6, 2),
  temp_c DECIMAL(5, 2),
  power_w DECIMAL(6, 2),
  latency_ms DECIMAL(8, 2),
  accuracy_pct DECIMAL(5, 2),
  PRIMARY KEY (id),
  FOREIGN KEY (session_id) REFERENCES board_session (id)
);
CREATE TABLE board_model_stat (
  cloud_board_id BIGINT NOT NULL,
  ai_model_id BIGINT NOT NULL,
  avg_fps DECIMAL(6, 2) NOT NULL DEFAULT 0,
  avg_accuracy DECIMAL(5, 2) NOT NULL DEFAULT 0,
  run_count INTEGER NOT NULL DEFAULT 0,
  updated_at TIMESTAMP NOT NULL,
  PRIMARY KEY (cloud_board_id, ai_model_id),
  FOREIGN KEY (cloud_board_id) REFERENCES cloud_board (id),
  FOREIGN KEY (ai_model_id) REFERENCES ai_model (id)
);
CREATE TABLE queue_entry (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  cloud_board_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  position INTEGER NOT NULL,
  state VARCHAR(20) NOT NULL DEFAULT 'WAITING' CHECK (state IN ('WAITING', 'READY', 'ENTERED', 'EXPIRED', 'CANCELLED')),
  created_at TIMESTAMP NOT NULL,
  notified_at TIMESTAMP,
  expires_at TIMESTAMP,
  PRIMARY KEY (id),
  FOREIGN KEY (cloud_board_id) REFERENCES cloud_board (id),
  FOREIGN KEY (user_id) REFERENCES users (id)
);
CREATE TABLE rental_board (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  name VARCHAR(100) NOT NULL,
  spec TEXT NOT NULL,
  photo_url VARCHAR(500),
  accessories VARCHAR(500),
  status VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE' CHECK (status IN ('AVAILABLE', 'RENTED', 'RETURN_PENDING', 'MAINTENANCE', 'BROKEN')),
  created_at TIMESTAMP NOT NULL,
  updated_at TIMESTAMP NOT NULL,
  deleted_at TIMESTAMP,
  PRIMARY KEY (id)
);
CREATE TABLE rental (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  rental_board_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'RENTED' CHECK (status IN ('RENTED', 'RETURN_REQUESTED', 'RETURNED')),
  rented_at TIMESTAMP NOT NULL,
  return_requested_at TIMESTAMP,
  returned_at TIMESTAMP,
  approved_by BIGINT,
  PRIMARY KEY (id),
  FOREIGN KEY (rental_board_id) REFERENCES rental_board (id),
  FOREIGN KEY (user_id) REFERENCES users (id),
  FOREIGN KEY (approved_by) REFERENCES users (id)
);
CREATE TABLE admin_action_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  admin_id BIGINT NOT NULL,
  action VARCHAR(50) NOT NULL,
  target_type VARCHAR(30) NOT NULL,
  target_id BIGINT NOT NULL,
  detail TEXT,
  created_at TIMESTAMP NOT NULL,
  PRIMARY KEY (id),
  FOREIGN KEY (admin_id) REFERENCES users (id)
);

-- 제약·인덱스 (ERDCloud MCP로는 UNIQUE·인덱스를 표현할 수 없어 여기에만 있다)
ALTER TABLE users ADD CONSTRAINT uk_users_email UNIQUE (email);
ALTER TABLE host_pi ADD CONSTRAINT uk_host_pi_serial UNIQUE (serial_code);
-- 소프트 삭제된 보드는 같은 시리얼·슬롯으로 다시 등록할 수 있게 부분 유니크
CREATE UNIQUE INDEX uk_cloud_board_serial ON cloud_board (serial_code) WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX uk_cloud_board_slot ON cloud_board (pi_id, usb_slot) WHERE deleted_at IS NULL;
-- 세션 모델 출처는 정확히 하나
ALTER TABLE board_session ADD CONSTRAINT ck_session_model_source CHECK ((ai_model_id IS NULL) <> (upload_id IS NULL));
-- 사용자당 활성 대기 1건 (MySQL 때의 생성 컬럼 우회 대신 부분 인덱스)
CREATE UNIQUE INDEX uk_queue_active_user ON queue_entry (user_id) WHERE state IN ('WAITING', 'READY');
-- 진행 중 세션은 보드당 1개
CREATE UNIQUE INDEX uk_session_active_board ON board_session (cloud_board_id) WHERE ended_at IS NULL;
CREATE INDEX ix_metric_session_time ON metric_sample (session_id, sampled_at);

